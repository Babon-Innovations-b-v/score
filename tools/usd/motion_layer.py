"""The motion layer of a place with its rigid moves: the rigid moves SCORE gives the things that move in their place
(the motion stage's moves.json, made from the design: score/stages/motion/from_design.py), with any timed motions
given beside them (tools/usd/motion.py), written over a stage folder's own layers.

    .venv/bin/python tools/usd/motion_layer.py <place> --stage <a stage folder> --out <folder for layers/motion.usda>
        --record <its rigid record>

A rigid record:

    {"place", "about", "seconds",            how many seconds of the stage's time the layer holds: every loop's round
                                             fits it a whole number of times, so the layer itself loops cleanly
     "moves": [{
        "name", "prim", "kind",              the moving prim, and its kind in data/checks/motion.json (its speeds)
        "on",                                what it moves on: "water" or "ground" (it keeps its height over that
                                             surface), "rail" (its slide or hinge holds it), "air"
        "start", "length", "loop",           as a motion record's: its round in seconds of the stage's time
        "path": {"points", "forward", "closed", "relative"}
                                             a closed round through the points ([x, z] in the prim's parent frame;
                                             offsets from its rest spot when `relative`), or an open drive from the
                                             first to the last (`closed`: false), a centripetal Catmull-Rom curve
                                             driven at one steady speed (its length over the round's), the prim's
                                             `forward` (its own axis, [0, 0, 1] by default) along the curve; its
                                             height kept where the base stands it, or on the ground following what is
                                             under it (write_layer's `ground`)
      | "swing": {"about", "angle", "speed", "starts", "moves"}
                                             a hinged leaf or a slewing crane: turning about the upright line through
                                             the middle of the prim `about` (a hinge; the prim itself for a slew),
                                             or a point on the leaf's own box (`about` {"side": [x, y, z]}: from
                                             its middle, each axis a share of its half size), `angle` degrees
                                             open (its sign the way round), at `speed` degrees a second, toward
                                             each end at its moment as a slide moves
      | "spin": {"speed", "about"}         a fan: turning steadily about the upright line through the middle of
                                             `about` (the prim itself by default) at `speed` degrees a second
      | "slide" | "turn" | "climb" | "light" as a motion record's (tools/usd/motion.py)
        "from"                               the measure, source or game line the moving thing's numbers came from
     }],
     "still": {<prim>: <why it stands still>}}   a thing of a moving kind that rightly does not move here

Each moving thing is written as an `over` with xform ops before the base's own: a path's `translate:path` and
`rotateY:path` round the prim's rest spot (`!invert!translate:rest`), a swing's `rotateY:swing` round its hinge
(`translate:hinge` and its inverse), a spin's `rotateY:spin` round its middle (`translate:spin`). Every sample is a
time code of the stage's own rate.
"""
import argparse
import json
import pathlib
import sys

import numpy as np
from pxr import Gf, Sdf, Usd, UsdGeom

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import motion  # noqa: E402

NOTE = "Generated by tools/usd/motion_layer.py from the place's rigid record; rewritten on every run."
# How many samples a second a path is written at: a ferry's 6 m/s on a 20 m turn strays 3 mm off its curve between.
PATH_SAMPLES = 8.0
# How finely the curve is cut to measure its length, pieces per waypoint.
CURVE_PIECES = 400
OWN_KINDS = ("path", "swing", "spin")


def kind_of(move):
    kinds = [kind for kind in (*OWN_KINDS, *motion.WRITERS) if kind in move]
    if len(kinds) != 1:
        raise ValueError(f"{move['name']}: a moving thing is one of {', '.join((*OWN_KINDS, *motion.WRITERS))}, not "
                         f"{kinds or 'none'}")
    return kinds[0]


# --- the curve ----------------------------------------------------------------------------------------------------

def closed_curve(points, pieces=CURVE_PIECES):
    """A closed centripetal Catmull-Rom curve through the points, cut fine: (spots [n, 2], length along it [n]); its
    last spot is its first again."""
    points = np.asarray(points, dtype=np.float64)
    count = len(points)
    if count < 3:
        raise ValueError("a closed path needs at least three points")
    spots = []
    for index in range(count):
        spots += list(piece(np.asarray([points[(index + step) % count] for step in (-1, 0, 1, 2)]), pieces))
    spots.append(points[0])
    spots = np.asarray(spots)
    along = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(spots, axis=0), axis=1))])
    return spots, along


def open_curve(points, pieces=CURVE_PIECES):
    """An open centripetal Catmull-Rom curve from the first point to the last (its ends' neighbours their mirrors),
    cut fine: (spots [n, 2], length along it [n])."""
    points = np.asarray(points, dtype=np.float64)
    if len(points) < 2:
        raise ValueError("an open path needs at least two points")
    padded = np.concatenate([[2 * points[0] - points[1]], points, [2 * points[-1] - points[-2]]])
    spots = []
    for index in range(1, len(padded) - 2):
        spots += list(piece(padded[index - 1:index + 3], pieces))
    spots.append(points[-1])
    spots = np.asarray(spots)
    along = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(spots, axis=0), axis=1))])
    return spots, along


def piece(four, pieces):
    """The centripetal Catmull-Rom curve between the middle two of four points, cut in `pieces`."""
    p0, p1, p2, p3 = four
    t0 = 0.0
    t1 = t0 + max(np.linalg.norm(p1 - p0), 1e-9) ** 0.5
    t2 = t1 + max(np.linalg.norm(p2 - p1), 1e-9) ** 0.5
    t3 = t2 + max(np.linalg.norm(p3 - p2), 1e-9) ** 0.5
    for knot in np.linspace(t1, t2, pieces, endpoint=False):
        a1 = (t1 - knot) / (t1 - t0) * p0 + (knot - t0) / (t1 - t0) * p1
        a2 = (t2 - knot) / (t2 - t1) * p1 + (knot - t1) / (t2 - t1) * p2
        a3 = (t3 - knot) / (t3 - t2) * p2 + (knot - t2) / (t3 - t2) * p3
        b1 = (t2 - knot) / (t2 - t0) * a1 + (knot - t0) / (t2 - t0) * a2
        b2 = (t3 - knot) / (t3 - t1) * a2 + (knot - t1) / (t3 - t1) * a3
        yield (t2 - knot) / (t2 - t1) * b1 + (knot - t1) / (t2 - t1) * b2


def curve_of(path, rest=None):
    """The path's curve: closed round its points, or open from the first to the last (`closed`: false); its points
    offsets from the prim's rest spot [x, z] when `relative`."""
    points = np.asarray(path["points"], dtype=np.float64)
    if path.get("relative"):
        points = points + np.asarray(rest, dtype=np.float64)
    return closed_curve(points) if path.get("closed", True) else open_curve(points)


def heading_of(way):
    """The turn about up, in degrees, that points +z along a way [x, z]."""
    return float(np.degrees(np.arctan2(way[0], way[1])))


def path_samples(path, length, seconds_in_round, rest=None):
    """Where a path's prim is at each of the moments (seconds into its round) driven at one speed along the curve:
    ([x, z] spots, headings in degrees unwrapped). An open path's heading at its end is the way it came in."""
    spots, along = curve_of(path, rest)
    reach = (np.asarray(seconds_in_round) / float(length)) * along[-1]
    xs = np.interp(reach, along, spots[:, 0])
    zs = np.interp(reach, along, spots[:, 1])
    if path.get("closed", True):  # the way half a metre on, wrapping over the start
        ahead = np.mod(reach + 0.5, along[-1])
        behind = reach
    else:  # the way along the half metre round it, inside the curve's ends
        ahead = np.minimum(reach + 0.5, along[-1])
        behind = np.maximum(ahead - 0.5, 0.0)
    ahead_x, ahead_z = np.interp(ahead, along, spots[:, 0]), np.interp(ahead, along, spots[:, 1])
    behind_x, behind_z = np.interp(behind, along, spots[:, 0]), np.interp(behind, along, spots[:, 1])
    headings = np.degrees(np.arctan2(ahead_x - behind_x, ahead_z - behind_z))
    return np.stack([xs, zs], axis=1), np.degrees(np.unwrap(np.radians(headings)))


def curve_length(path, rest=None):
    return float(curve_of(path, rest)[1][-1])


# --- the rest pose ------------------------------------------------------------------------------------------------

def rest_local(stage, path):
    """The prim's local transform where the base stands it (a numpy 4x4, row vectors as OpenUSD writes them)."""
    prim = stage.GetPrimAtPath(path)
    if not prim:
        raise ValueError(f"the stage has no prim {path}")
    return np.asarray(UsdGeom.Xformable(prim).GetLocalTransformation(Usd.TimeCode.Default()))


def parent_inverse(stage, path):
    """The world-to-parent transform of the prim's parent (row vectors)."""
    parent = stage.GetPrimAtPath(path).GetParent()
    world = np.asarray(UsdGeom.Xformable(parent).ComputeLocalToWorldTransform(Usd.TimeCode.Default())) \
        if parent.IsA(UsdGeom.Xformable) else np.eye(4)
    return np.linalg.inv(world)


def prepend_ops(stage, path, ops):
    """The prim's xform op order in the layer with `ops` (names, outermost first) before the base's own."""
    order = list(UsdGeom.Xformable(stage.GetPrimAtPath(path)).GetXformOpOrderAttr().Get() or [])
    stage.OverridePrim(path).CreateAttribute("xformOpOrder", Sdf.ValueTypeNames.TokenArray).Set([*ops, *order])


# --- writers ------------------------------------------------------------------------------------------------------

def write_path(stage, move, rate, seconds, ground=None):
    """A prim driven along its path: its rest spot carried along the curve and turned to face along it. On the
    ground (`on`: "ground", given `ground`: the height of what is under each [x, z] spot) it rises and falls with what
    is under it, kept as high over it as where it rests (`ground(spots, turns)`: the height of what is under its
    footprint carried to each [x, z] spot and turned by each turn, degrees from its rest heading)."""
    path, prim_path = move["path"], move["prim"]
    local = rest_local(stage, prim_path)
    rest = local[3, :3]
    forward = np.asarray(path.get("forward", (0.0, 0.0, 1.0)), dtype=np.float64) @ local[:3, :3]
    rest_heading = heading_of((forward[0], forward[2]))
    start, length = float(move.get("start", 0.0)), float(move["length"])
    moments = np.arange(start, seconds + 1e-9, 1.0 / PATH_SAMPLES)
    into = np.mod(moments - start, length) if move.get("loop") else np.minimum(moments - start, length)
    spots, headings = path_samples(path, length, into, rest[[0, 2]])  # unwrapped: a seam does not spin back
    heights = np.full(len(spots), rest[1])
    if move.get("on") == "ground" and ground is not None:
        under = ground(np.vstack([rest[[0, 2]], spots]), np.concatenate([[0.0], headings - rest_heading]))
        if np.isnan(under).any():
            raise ValueError(f"{move['name']}: its path leaves what is under it")
        heights = rest[1] + under[1:] - under[0]
    prim = stage.OverridePrim(prim_path)
    moved = prim.CreateAttribute("xformOp:translate:path", Sdf.ValueTypeNames.Double3)
    turned = prim.CreateAttribute("xformOp:rotateY:path", Sdf.ValueTypeNames.Double)
    prim.CreateAttribute("xformOp:translate:rest", Sdf.ValueTypeNames.Double3).Set(Gf.Vec3d(*rest))
    prepend_ops(stage, prim_path, ["xformOp:translate:path", "xformOp:rotateY:path", "!invert!xformOp:translate:rest"])
    # read without a time (the resting checks) it stands at rest: with samples alone the garage's rover read 0.9 m
    # off its spot, in its lift (2026-10-15)
    moved.Set(Gf.Vec3d(*rest))
    turned.Set(0.0)
    for moment, spot, height, heading in zip(moments, spots, heights, headings):
        moved.Set(Gf.Vec3d(float(spot[0]), float(height), float(spot[1])), motion.code(moment, rate))
        turned.Set(float(heading - rest_heading), motion.code(moment, rate))


def hinge_spot(stage, move, about):
    """The middle of the `about` prim where the base stands it, or (`about` {"side": [x, y, z]}) the point on the
    moving thing's own box that far from its middle, each axis a share of its half size, in the moving thing's
    parent frame."""
    if isinstance(about, dict):
        return own_side(stage, move, about["side"])
    place = move["prim"].split("/")[1]
    found = stage.GetPrimAtPath(about if about.startswith("/") else f"/{place}/{about}")
    if not found:
        raise ValueError(f"{move['name']}: the stage has no hinge prim {about}")
    box = UsdGeom.BBoxCache(Usd.TimeCode.Default(), ["default", "render"]).ComputeWorldBound(found)
    middle = np.asarray(box.ComputeAlignedRange().GetMidpoint(), dtype=np.float64)
    return np.append(middle, 1.0) @ parent_inverse(stage, move["prim"])


def own_side(stage, move, side):
    """The point on the moving prim's own box `side` from its middle (each axis a share of its half size), where the
    base stands it, in its parent frame."""
    prim = stage.GetPrimAtPath(move["prim"])
    if not prim:
        raise ValueError(f"{move['name']}: the stage has no prim {move['prim']}")
    box = UsdGeom.BBoxCache(Usd.TimeCode.Default(), ["default", "render"]).ComputeUntransformedBound(prim)
    low, high = (np.asarray(corner, dtype=np.float64) for corner in (box.ComputeAlignedRange().GetMin(),
                                                                     box.ComputeAlignedRange().GetMax()))
    point = (low + high) / 2 + np.asarray(side, dtype=np.float64) * (high - low) / 2
    own = np.asarray(UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(Usd.TimeCode.Default()))
    return np.append(point, 1.0) @ own @ parent_inverse(stage, move["prim"])


def write_swing(stage, move, rate, seconds):
    """A leaf turned about the upright line through its hinge, toward each end at its moment at its speed."""
    swing = move["swing"]
    hinge = hinge_spot(stage, move, swing["about"])[:3]
    keys = motion.slide_keys({"by": [abs(float(swing["angle"])), 0.0, 0.0], "speed": float(swing["speed"]),
                              "starts": swing.get("starts", motion.SHUT), "moves": swing["moves"]})
    prim = stage.OverridePrim(move["prim"])
    prim.CreateAttribute("xformOp:translate:hinge", Sdf.ValueTypeNames.Double3).Set(Gf.Vec3d(*hinge))
    turned = prim.CreateAttribute("xformOp:rotateY:swing", Sdf.ValueTypeNames.Double)
    prepend_ops(stage, move["prim"], ["xformOp:translate:hinge", "xformOp:rotateY:swing",
                                       "!invert!xformOp:translate:hinge"])
    for moment, share in motion.rounds(keys, move, seconds):
        turned.Set(float(swing["angle"]) * share, motion.code(moment, rate))


def write_spin(stage, move, rate, seconds):
    """A prim turned steadily about the upright line through the middle of `about` (its own middle by default), at
    `speed` degrees a second from its start to the layer's end."""
    spin = move["spin"]
    hinge = hinge_spot(stage, move, spin.get("about", move["prim"]))[:3]
    start = float(move.get("start", 0.0))
    prim = stage.OverridePrim(move["prim"])
    prim.CreateAttribute("xformOp:translate:spin", Sdf.ValueTypeNames.Double3).Set(Gf.Vec3d(*hinge))
    turned = prim.CreateAttribute("xformOp:rotateY:spin", Sdf.ValueTypeNames.Double)
    prepend_ops(stage, move["prim"], ["xformOp:translate:spin", "xformOp:rotateY:spin",
                                       "!invert!xformOp:translate:spin"])
    turned.Set(0.0, motion.code(start, rate))
    turned.Set(float(spin["speed"]) * (seconds - start), motion.code(seconds, rate))


WRITERS = {"path": write_path, "swing": write_swing, "spin": write_spin, **motion.WRITERS}


# --- the layer ----------------------------------------------------------------------------------------------------

def place_only(place, source, moving):
    """The population mask of the place itself: every scope of its own but the places it shows (`Places`, each
    another place's whole stage, which may show this one back), and of those only the prims that move (the garage's
    door leaves, kits of their own)."""
    root = Sdf.Layer.FindOrOpen(str(pathlib.Path(source) / f"{place}.usda"))
    names = set()
    for path in root.subLayerPaths:
        layer = Sdf.Layer.FindOrOpen(str(pathlib.Path(source) / path))
        spec = layer.GetPrimAtPath(f"/{place}") if layer else None
        names |= {child.name for child in spec.nameChildren} if spec else set()
    mask = Usd.StagePopulationMask()
    for name in sorted(names - {"Places"}):
        mask.Add(Sdf.Path(f"/{place}/{name}"))
    for path in moving:
        if path.startswith(f"/{place}/Places/"):
            mask.Add(Sdf.Path(path))
    return mask


def working_stage(place, source, layer, moving):
    """The place's own stage (place_only) with the motion layer strongest of its root's layers and every write going
    into it, so what the layer adds is read back composed with the base it stands on."""
    root = Sdf.Layer.FindOrOpen(str(pathlib.Path(source) / f"{place}.usda"))
    if root is None:
        raise ValueError(f"no stage at {source}/{place}.usda")
    others = [str(pathlib.Path(source) / path) for path in root.subLayerPaths if path != f"./{motion.LAYER}"]
    stand_in = Sdf.Layer.CreateAnonymous(".usda")
    stand_in.subLayerPaths[:] = [layer.identifier, *others]
    stage = Usd.Stage.OpenMasked(stand_in, place_only(place, source, moving))
    stage.SetEditTarget(Usd.EditTarget(layer))
    return stage


def moving_prims(entries):
    """Every prim the motions move or copy."""
    return [path for entry in entries for path in (entry["prim"], entry.get("adds", {}).get("like")) if path]


def round_faults(moves, seconds):
    """A looping moving thing whose round does not fit the layer's seconds a whole number of times breaks the layer's loop."""
    faults = []
    for move in moves:
        if move.get("loop"):
            rounds = (seconds - float(move.get("start", 0.0))) / float(move["length"])
            if abs(rounds - round(rounds)) > 1e-6:
                faults.append(f"{move['name']}: its {move['length']} s round fits the layer's {seconds} s "
                              f"{rounds:.3f} times")
    return faults


def write_layer(place, motions, moves, source, out, ground=None):
    """The motion layer of the place's stage in `source` (a stage folder: its root and layers), written to
    `out`/layers/motion.usda, rewritten whole; what it moved, by name."""
    seconds = float((moves or {}).get("seconds", motion.WRITTEN_SECONDS))
    faults = round_faults((moves or {}).get("moves", []), seconds)
    if faults:
        raise ValueError("; ".join(faults))
    rate = motion.stage_rate(place, source)
    path = pathlib.Path(out) / motion.LAYER
    path.parent.mkdir(parents=True, exist_ok=True)
    layer = Sdf.Layer.FindOrOpen(str(path)) or Sdf.Layer.CreateNew(str(path))
    layer.Clear()
    layer.documentation = NOTE
    layer.timeCodesPerSecond = rate
    layer.framesPerSecond = rate
    layer.startTimeCode = 0.0
    layer.endTimeCode = seconds * rate
    every = [*(motions or {}).get("motions", []), *(moves or {}).get("moves", [])]
    stage = working_stage(place, source, layer, moving_prims(every))
    moved = []
    for entry in every:
        if "adds" in entry:
            motion.added(stage, entry)
        if kind_of(entry) == "path":
            write_path(stage, entry, rate, seconds, ground and ground(stage, entry))
        else:
            WRITERS[kind_of(entry)](stage, entry, rate, seconds)
        prim = stage.GetPrimAtPath(entry["prim"])
        prim.CreateAttribute("score:motion:from", Sdf.ValueTypeNames.String).Set(entry.get("from", ""))
        if "kind" in entry:
            prim.CreateAttribute("score:motion:kind", Sdf.ValueTypeNames.String).Set(entry["kind"])
        moved.append(entry["name"])
    for prim in layer.rootPrims:  # the place and its scopes are the base's
        motion.overs(prim)
    layer.Save()
    return {"moved": moved, "seconds": seconds, "layer": str(path)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("place")
    parser.add_argument("--stage", required=True, type=pathlib.Path, help="the place's stage folder")
    parser.add_argument("--out", required=True, type=pathlib.Path, help="where layers/motion.usda is written")
    parser.add_argument("--record", required=True, type=pathlib.Path,
                        help="the place's rigid record (the motion row's moves.json, made from its design)")
    arguments = parser.parse_args()
    print(json.dumps(write_layer(arguments.place, None, json.loads(arguments.record.read_text()), arguments.stage,
                                 arguments.out)))


if __name__ == "__main__":
    main()
