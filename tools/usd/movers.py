"""The motion layer of a place with its movers: the game's timed motions (data/motion, tools/usd/motion.py) and the
movers SCORE gives the things that move in their place (data/movers), written over a stage folder's own layers.

    .venv/bin/python tools/usd/movers.py <place> --stage <a stage folder> --out <folder for layers/motion.usda>

A movers record:

    {"place", "about", "seconds",            how many seconds of the stage's time the layer holds: every loop's round
                                             fits it a whole number of times, so the layer itself loops cleanly
     "movers": [{
        "name", "prim", "kind",              the moving prim, and its kind in data/checks/motion.json (its speeds)
        "on",                                what it moves on: "water" or "ground" (it keeps its height over that
                                             surface), "rail" (its slide or hinge holds it), "air"
        "start", "length", "loop",           as a motion record's: its round in seconds of the stage's time
        "path": {"points", "forward"}        a closed round through the points ([x, z] in the prim's parent frame),
                                             a centripetal Catmull-Rom curve driven at one steady speed (its length
                                             over the round's), the prim's `forward` (its own axis, [0, 0, 1] by
                                             default) along the curve and its height kept where the base stands it
      | "swing": {"about", "angle", "speed", "starts", "moves"}
                                             a hinged leaf or a slewing crane: turning about the upright line through
                                             the middle of the prim `about` (a hinge; the prim itself for a slew),
                                             `angle` degrees open (its sign the way round), at `speed` degrees a
                                             second, toward each end at its moment as a slide moves
      | "spin": {"speed", "about"}         a fan: turning steadily about the upright line through the middle of
                                             `about` (the prim itself by default) at `speed` degrees a second
      | "slide" | "turn" | "climb" | "light" as a motion record's (tools/usd/motion.py)
        "from"                               the measure, source or game line the mover's numbers came from
     }],
     "still": {<prim>: <why it stands still>}}   a thing of a moving kind that rightly does not move here

Each mover is written as an `over` with xform ops before the base's own: a path's `translate:path` and
`rotateY:path` round the prim's rest spot (`!invert!translate:rest`), a swing's `rotateY:swing` round its hinge
(`translate:hinge` and its inverse), a spin's `rotateY:spin` round its middle (`translate:spin`). Every sample is a time code of the stage's own rate.
"""
import argparse
import json
import pathlib
import sys

import numpy as np
from pxr import Gf, Sdf, Usd, UsdGeom

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
import motion  # noqa: E402

MOVERS = REPO / "data/movers"
NOTE = ("Generated by tools/usd/movers.py from the place's motion record (data/motion) and movers record "
        "(data/movers); rewritten on every run.")
# How many samples a second a path is written at: a ferry's 6 m/s on a 20 m turn strays 3 mm off its curve between.
PATH_SAMPLES = 8.0
# How finely the curve is cut to measure its length, pieces per waypoint.
CURVE_PIECES = 400
OWN_KINDS = ("path", "swing", "spin")


def record(place):
    """The place's movers record, or None for a place with none."""
    path = MOVERS / f"{place}.json"
    return json.loads(path.read_text()) if path.exists() else None


def kind_of(mover):
    kinds = [kind for kind in (*OWN_KINDS, *motion.WRITERS) if kind in mover]
    if len(kinds) != 1:
        raise ValueError(f"{mover['name']}: a mover is one of {', '.join((*OWN_KINDS, *motion.WRITERS))}, not "
                         f"{kinds or 'none'}")
    return kinds[0]


# --- the curve ----------------------------------------------------------------------------------------------------

def closed_curve(points, pieces=CURVE_PIECES):
    """A closed centripetal Catmull-Rom curve through the points, cut fine: (spots [n, 2], length along it [n]); its
    last spot is its first again."""
    points = np.asarray(points, dtype=np.float64)
    count = len(points)
    if count < 3:
        raise ValueError("a closed path needs at least three points")
    spots = []
    for index in range(count):
        p0, p1, p2, p3 = (points[(index + step) % count] for step in (-1, 0, 1, 2))
        t0 = 0.0
        t1 = t0 + max(np.linalg.norm(p1 - p0), 1e-9) ** 0.5
        t2 = t1 + max(np.linalg.norm(p2 - p1), 1e-9) ** 0.5
        t3 = t2 + max(np.linalg.norm(p3 - p2), 1e-9) ** 0.5
        for knot in np.linspace(t1, t2, pieces, endpoint=False):
            a1 = (t1 - knot) / (t1 - t0) * p0 + (knot - t0) / (t1 - t0) * p1
            a2 = (t2 - knot) / (t2 - t1) * p1 + (knot - t1) / (t2 - t1) * p2
            a3 = (t3 - knot) / (t3 - t2) * p2 + (knot - t2) / (t3 - t2) * p3
            b1 = (t2 - knot) / (t2 - t0) * a1 + (knot - t0) / (t2 - t0) * a2
            b2 = (t3 - knot) / (t3 - t1) * a2 + (knot - t1) / (t3 - t1) * a3
            spots.append((t2 - knot) / (t2 - t1) * b1 + (knot - t1) / (t2 - t1) * b2)
    spots.append(points[0])
    spots = np.asarray(spots)
    along = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(spots, axis=0), axis=1))])
    return spots, along


def heading_of(way):
    """The turn about up, in degrees, that points +z along a way [x, z]."""
    return float(np.degrees(np.arctan2(way[0], way[1])))


def path_samples(path, length, seconds_in_round):
    """Where a path's prim is at each of the moments (seconds into its round) driven at one speed round the curve:
    ([x, z] spots, headings in degrees unwrapped)."""
    spots, along = closed_curve(path["points"])
    reach = (np.asarray(seconds_in_round) / float(length)) * along[-1]
    xs = np.interp(reach, along, spots[:, 0])
    zs = np.interp(reach, along, spots[:, 1])
    ahead = np.minimum(reach + 0.5, along[-1] + 0.5)  # the way half a metre on (wrapping over the start)
    ahead_x = np.interp(np.mod(ahead, along[-1]), along, spots[:, 0])
    ahead_z = np.interp(np.mod(ahead, along[-1]), along, spots[:, 1])
    headings = np.degrees(np.arctan2(ahead_x - xs, ahead_z - zs))
    return np.stack([xs, zs], axis=1), np.degrees(np.unwrap(np.radians(headings)))


def curve_length(path):
    return float(closed_curve(path["points"])[1][-1])


# --- the rest pose ------------------------------------------------------------------------------------------------

def rest_local(stage, path):
    """The prim's local transform where the base stands it (a numpy 4x4, row vectors as OpenUSD writes them)."""
    prim = stage.GetPrimAtPath(path)
    if not prim:
        raise ValueError(f"the stage has no prim {path}")
    return np.asarray(UsdGeom.Xformable(prim).GetLocalTransformation(Usd.TimeCode.Default()))


def parent_inverse(stage, path):
    """The world-to-parent transform of the prim's parent (row vectors)."""
    parent = stage.GetPrimAtPath(path).GetParent()
    world = np.asarray(UsdGeom.Xformable(parent).ComputeLocalToWorldTransform(Usd.TimeCode.Default())) \
        if parent.IsA(UsdGeom.Xformable) else np.eye(4)
    return np.linalg.inv(world)


def prepend_ops(stage, path, ops):
    """The prim's xform op order in the layer with `ops` (names, outermost first) before the base's own."""
    order = list(UsdGeom.Xformable(stage.GetPrimAtPath(path)).GetXformOpOrderAttr().Get() or [])
    stage.OverridePrim(path).CreateAttribute("xformOpOrder", Sdf.ValueTypeNames.TokenArray).Set([*ops, *order])


# --- writers ------------------------------------------------------------------------------------------------------

def write_path(stage, mover, rate, seconds):
    """A prim driven round its closed path: its rest spot carried along the curve and turned to face along it."""
    path, prim_path = mover["path"], mover["prim"]
    local = rest_local(stage, prim_path)
    rest = local[3, :3]
    forward = np.asarray(path.get("forward", (0.0, 0.0, 1.0)), dtype=np.float64) @ local[:3, :3]
    rest_heading = heading_of((forward[0], forward[2]))
    start, length = float(mover.get("start", 0.0)), float(mover["length"])
    moments = np.arange(start, seconds + 1e-9, 1.0 / PATH_SAMPLES)
    into = np.mod(moments - start, length) if mover.get("loop") else np.minimum(moments - start, length)
    spots, headings = path_samples(path, length, into)  # unwrapped over every round, so a seam does not spin back
    prim = stage.OverridePrim(prim_path)
    moved = prim.CreateAttribute("xformOp:translate:path", Sdf.ValueTypeNames.Double3)
    turned = prim.CreateAttribute("xformOp:rotateY:path", Sdf.ValueTypeNames.Double)
    prim.CreateAttribute("xformOp:translate:rest", Sdf.ValueTypeNames.Double3).Set(Gf.Vec3d(*rest))
    prepend_ops(stage, prim_path, ["xformOp:translate:path", "xformOp:rotateY:path", "!invert!xformOp:translate:rest"])
    for moment, spot, heading in zip(moments, spots, headings):
        moved.Set(Gf.Vec3d(float(spot[0]), float(rest[1]), float(spot[1])), motion.code(moment, rate))
        turned.Set(float(heading - rest_heading), motion.code(moment, rate))


def hinge_spot(stage, mover, about):
    """The middle of the `about` prim where the base stands it, in the mover's parent frame."""
    place = mover["prim"].split("/")[1]
    found = stage.GetPrimAtPath(about if about.startswith("/") else f"/{place}/{about}")
    if not found:
        raise ValueError(f"{mover['name']}: the stage has no hinge prim {about}")
    box = UsdGeom.BBoxCache(Usd.TimeCode.Default(), ["default", "render"]).ComputeWorldBound(found)
    middle = np.asarray(box.ComputeAlignedRange().GetMidpoint(), dtype=np.float64)
    return np.append(middle, 1.0) @ parent_inverse(stage, mover["prim"])


def write_swing(stage, mover, rate, seconds):
    """A leaf turned about the upright line through its hinge, toward each end at its moment at its speed."""
    swing = mover["swing"]
    hinge = hinge_spot(stage, mover, swing["about"])[:3]
    keys = motion.slide_keys({"by": [abs(float(swing["angle"])), 0.0, 0.0], "speed": float(swing["speed"]),
                              "starts": swing.get("starts", motion.SHUT), "moves": swing["moves"]})
    prim = stage.OverridePrim(mover["prim"])
    prim.CreateAttribute("xformOp:translate:hinge", Sdf.ValueTypeNames.Double3).Set(Gf.Vec3d(*hinge))
    turned = prim.CreateAttribute("xformOp:rotateY:swing", Sdf.ValueTypeNames.Double)
    prepend_ops(stage, mover["prim"], ["xformOp:translate:hinge", "xformOp:rotateY:swing",
                                       "!invert!xformOp:translate:hinge"])
    for moment, share in motion.rounds(keys, mover, seconds):
        turned.Set(float(swing["angle"]) * share, motion.code(moment, rate))


def write_spin(stage, mover, rate, seconds):
    """A prim turned steadily about the upright line through the middle of `about` (its own middle by default), at
    `speed` degrees a second from its start to the layer's end."""
    spin = mover["spin"]
    hinge = hinge_spot(stage, mover, spin.get("about", mover["prim"]))[:3]
    start = float(mover.get("start", 0.0))
    prim = stage.OverridePrim(mover["prim"])
    prim.CreateAttribute("xformOp:translate:spin", Sdf.ValueTypeNames.Double3).Set(Gf.Vec3d(*hinge))
    turned = prim.CreateAttribute("xformOp:rotateY:spin", Sdf.ValueTypeNames.Double)
    prepend_ops(stage, mover["prim"], ["xformOp:translate:spin", "xformOp:rotateY:spin",
                                       "!invert!xformOp:translate:spin"])
    turned.Set(0.0, motion.code(start, rate))
    turned.Set(float(spin["speed"]) * (seconds - start), motion.code(seconds, rate))


WRITERS = {"path": write_path, "swing": write_swing, "spin": write_spin, **motion.WRITERS}


# --- the layer ----------------------------------------------------------------------------------------------------

def round_faults(movers, seconds):
    """A looping mover whose round does not fit the layer's seconds a whole number of times breaks the layer's loop."""
    faults = []
    for mover in movers:
        if mover.get("loop"):
            rounds = (seconds - float(mover.get("start", 0.0))) / float(mover["length"])
            if abs(rounds - round(rounds)) > 1e-6:
                faults.append(f"{mover['name']}: its {mover['length']} s round fits the layer's {seconds} s "
                              f"{rounds:.3f} times")
    return faults


def write_layer(place, motions, movers, source, out):
    """The motion layer of the place's stage in `source` (a stage folder: its root and layers), written to
    `out`/layers/motion.usda, rewritten whole; what it moved, by name."""
    seconds = float((movers or {}).get("seconds", motion.WRITTEN_SECONDS))
    faults = round_faults((movers or {}).get("movers", []), seconds)
    if faults:
        raise ValueError("; ".join(faults))
    rate = motion.stage_rate(place, source)
    path = pathlib.Path(out) / motion.LAYER
    path.parent.mkdir(parents=True, exist_ok=True)
    layer = Sdf.Layer.FindOrOpen(str(path)) or Sdf.Layer.CreateNew(str(path))
    layer.Clear()
    layer.documentation = NOTE
    layer.timeCodesPerSecond = rate
    layer.framesPerSecond = rate
    layer.startTimeCode = 0.0
    layer.endTimeCode = seconds * rate
    stage = motion.working_stage(place, source, layer)
    moved = []
    for entry in [*(motions or {}).get("motions", []), *(movers or {}).get("movers", [])]:
        if "adds" in entry:
            motion.added(stage, entry)
        WRITERS[kind_of(entry)](stage, entry, rate, seconds)
        prim = stage.GetPrimAtPath(entry["prim"])
        prim.CreateAttribute("score:motion:from", Sdf.ValueTypeNames.String).Set(entry.get("from", ""))
        if "kind" in entry:
            prim.CreateAttribute("score:motion:kind", Sdf.ValueTypeNames.String).Set(entry["kind"])
        moved.append(entry["name"])
    for prim in layer.rootPrims:  # the place and its scopes are the base's
        motion.overs(prim)
    layer.Save()
    return {"moved": moved, "seconds": seconds, "layer": str(path)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("place")
    parser.add_argument("--stage", required=True, type=pathlib.Path, help="the place's stage folder")
    parser.add_argument("--out", required=True, type=pathlib.Path, help="where layers/motion.usda is written")
    arguments = parser.parse_args()
    print(json.dumps(write_layer(arguments.place, motion.record(arguments.place), record(arguments.place),
                                 arguments.stage, arguments.out)))


if __name__ == "__main__":
    main()
