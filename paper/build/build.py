#!/usr/bin/env python3
"""Build the SCORE paper from its one Markdown source, or check the build is current.

    python3 paper/build/build.py           # build everything, then write the stamp
    python3 paper/build/build.py --check   # exit 1 when a committed output is stale

The source is paper/source/score.md, with refs.bib, the IEEE citation style and the
TODO filter beside it, and the pictures in paper/figures/. Two outputs come from it:

- paper/out/score.tex and score.pdf: pandoc's own standalone rendering, citations
  resolved by citeproc with the IEEE style.
- paper/arxiv/: an arXiv-ready LaTeX tree (main.tex, content/, figures/, refs.bib and the
  main.bbl arXiv needs, since it does not run BibTeX), and its main.pdf.

Every .tex under paper/arxiv/ is generated: edit the Markdown, never the LaTeX.

The PDF engine is xelatex when it is installed, else tectonic. Nothing is installed by
this script.

"Current" means: the stamp (paper/out/stamp.json) records a hash of every input and
every output, and the files on disk still match it. A draft edited without a rebuild,
or a generated file edited by hand, fails the check.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
SOURCE = PAPER / "source"
FIGURES = PAPER / "figures"
OUT = PAPER / "out"
ARXIV = PAPER / "arxiv"
DRAFT = SOURCE / "score.md"
STAMP = OUT / "stamp.json"

FILTER = SOURCE / "markers.lua"
BIB = SOURCE / "refs.bib"
CSL = SOURCE / "ieee.csl"

HEADING = re.compile(r"^# (?P<title>.+?)\s*(\{-\})?\s*$")
FRONT_MATTER = re.compile(r"\A---\n(?P<yaml>.*?)\n---\n", re.DOTALL)
SKIPPED_IN_ARXIV = {"References"}
# Sections from this heading on go after the bibliography in the arXiv tree.
APPENDIX_TITLE = "Appendix"
INTERMEDIATE_SUFFIXES = (".aux", ".log", ".out", ".blg", ".toc", ".fls", ".fdb_latexmk")

PREAMBLE = r"""\documentclass[11pt]{article}

% Generated by paper/build/build.py from paper/source/score.md. Do not edit.
\usepackage{iftex}
\ifPDFTeX
  \usepackage[T1]{fontenc}
  \usepackage[utf8]{inputenc}
  \usepackage{lmodern}
  \usepackage{textcomp}
\else
  \usepackage{fontspec}
\fi
\usepackage{amsmath,amssymb}
\usepackage{longtable,booktabs,array,calc}
\usepackage{graphicx}
\usepackage{xcolor}
\usepackage[numbers,sort&compress]{natbib}
\usepackage{microtype}
\usepackage[margin=2.5cm]{geometry}
\usepackage[colorlinks=true,linkcolor=blue,citecolor=blue,urlcolor=blue]{hyperref}
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\providecommand{\pandocbounded}[1]{#1}
\setlength{\emergencystretch}{3em}
"""


def run(command: list[str], cwd: Path) -> None:
    """Run one tool and stop the build with its own message when it fails."""
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"{command[0]} failed:\n{result.stderr.strip() or result.stdout.strip()}")


def pdf_engine() -> str:
    """xelatex when it is installed, else tectonic; fail plainly when neither is."""
    for engine in ("xelatex", "tectonic"):
        if shutil.which(engine):
            return engine
    sys.exit("No PDF engine: install TeX Live (xelatex) or tectonic, then build again.")


def build_standalone() -> None:
    """Render the draft with pandoc into out/score.tex and out/score.pdf."""
    OUT.mkdir(parents=True, exist_ok=True)
    common = [
        "pandoc", str(DRAFT),
        "--number-sections",
        "--citeproc", f"--bibliography={BIB}", f"--csl={CSL}",
        f"--lua-filter={FILTER}",
        "-V", "geometry:margin=2.5cm", "-V", "fontsize=11pt", "-V", "colorlinks=true",
        "--standalone",
    ]
    run(common + ["-o", str(OUT / "score.tex")], cwd=PAPER)
    run(common + [f"--pdf-engine={pdf_engine()}", "-o", str(OUT / "score.pdf")], cwd=PAPER)


def split_front_matter(text: str) -> tuple[str, str]:
    """The draft's YAML front matter and its body, separately."""
    match = FRONT_MATTER.match(text)
    if match is None:
        sys.exit("score.md must start with YAML front matter (title, author, abstract).")
    return match.group("yaml"), text[match.end():]


def split_sections(body: str) -> list[tuple[str, str]]:
    """The body as (title, markdown) chunks, one per top-level heading.

    Anything before the first heading (a teaser figure) becomes a chunk titled "Teaser".
    """
    sections: list[tuple[str, list[str]]] = [("Teaser", [])]
    for line in body.splitlines():
        heading = HEADING.match(line)
        if heading:
            sections.append((heading.group("title"), [line]))
        else:
            sections[-1][1].append(line)
    return [(title, "\n".join(lines) + "\n") for title, lines in sections if "".join(lines).strip()]


def slug(title: str) -> str:
    """A file name for a section title: lower case, words joined by underscores."""
    return re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")


def markdown_to_latex(markdown: str) -> str:
    """One chunk of the draft as LaTeX for the arXiv tree, citations left to natbib."""
    result = subprocess.run(
        ["pandoc", "--from=markdown", "--to=latex", "--natbib", "--wrap=preserve",
         f"--lua-filter={FILTER}"],
        input=markdown, capture_output=True, text=True, cwd=PAPER,
    )
    if result.returncode != 0:
        sys.exit(f"pandoc failed on a section:\n{result.stderr.strip()}")
    return result.stdout


def front_matter_latex(yaml_text: str) -> tuple[str, str, str, str]:
    """Title, author, date and abstract from the front matter, rendered as LaTeX."""
    with tempfile.TemporaryDirectory() as scratch:
        template = Path(scratch) / "front.tex"
        template.write_text(
            "$title$\n%%SPLIT%%\n$for(author)$$author$$sep$ \\and $endfor$\n%%SPLIT%%\n"
            "$date$\n%%SPLIT%%\n$abstract$\n"
        )
        result = subprocess.run(
            ["pandoc", "--from=markdown", "--to=latex", f"--template={template}",
             f"--lua-filter={FILTER}"],
            input=f"---\n{yaml_text}\n---\n", capture_output=True, text=True,
        )
    if result.returncode != 0:
        sys.exit(f"pandoc failed on the front matter:\n{result.stderr.strip()}")
    title, author, date, abstract = (part.strip() for part in result.stdout.split("%%SPLIT%%"))
    return title, author, date, abstract


def write_arxiv_sources(text: str) -> None:
    """Write main.tex, content/*.tex, refs.bib and figures/ for the arXiv tree."""
    yaml_text, body = split_front_matter(text)
    title, author, date, abstract = front_matter_latex(yaml_text)
    if ARXIV.exists():
        shutil.rmtree(ARXIV)
    (ARXIV / "content").mkdir(parents=True)
    inputs, appendix = [], []
    for section_title, markdown in split_sections(body):
        if section_title in SKIPPED_IN_ARXIV:
            continue
        name = slug(section_title)
        (ARXIV / "content" / f"{name}.tex").write_text(markdown_to_latex(markdown))
        target = appendix if appendix or section_title == APPENDIX_TITLE else inputs
        target.append(f"\\input{{content/{name}}}")
    (ARXIV / "content" / "abstract.tex").write_text(
        f"\\begin{{abstract}}\n{abstract}\n\\end{{abstract}}\n"
    )
    main = (
        PREAMBLE
        + f"\n\\title{{{title}}}\n\\author{{{author}}}\n\\date{{{date}}}\n\n"
        + "\\begin{document}\n\\maketitle\n\\input{content/abstract}\n\n"
        + "\n".join(inputs)
        + "\n\n\\bibliographystyle{unsrtnat}\n\\bibliography{refs}\n\n"
        + "\n".join(appendix)
        + "\n\\end{document}\n"
    )
    (ARXIV / "main.tex").write_text(main)
    shutil.copy2(BIB, ARXIV / "refs.bib")
    if FIGURES.exists():
        shutil.copytree(FIGURES, ARXIV / "figures")


def compile_arxiv() -> None:
    """Compile the arXiv tree to main.pdf, keeping main.bbl and nothing else of the run."""
    if pdf_engine() == "tectonic":
        run(["tectonic", "-X", "compile", "--keep-intermediates", "main.tex"], cwd=ARXIV)
    else:
        latex = ["xelatex", "-interaction=nonstopmode", "-halt-on-error", "main.tex"]
        for command in (latex, ["bibtex", "main"], latex, latex):
            run(command, cwd=ARXIV)
    for leftover in ARXIV.iterdir():
        if leftover.suffix in INTERMEDIATE_SUFFIXES:
            leftover.unlink()


def tracked_files() -> dict[str, list[Path]]:
    """Every input and every output the stamp covers, by role."""
    figures = sorted(FIGURES.iterdir()) if FIGURES.exists() else []
    inputs = [DRAFT, BIB, CSL, FILTER, Path(__file__).resolve(), *figures]
    outputs = [OUT / "score.tex", OUT / "score.pdf", *sorted(
        path for path in ARXIV.rglob("*") if path.is_file()
    )]
    return {"inputs": inputs, "outputs": outputs}


def file_hash(path: Path) -> str:
    """sha256 of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def current_hashes() -> dict[str, dict[str, str]]:
    """The hash of every tracked file as it is on disk now, keyed by its path in the repo."""
    root = PAPER.parent
    return {
        role: {str(path.relative_to(root)): file_hash(path) for path in paths if path.exists()}
        for role, paths in tracked_files().items()
    }


def write_stamp() -> None:
    """Record the hashes of this build's inputs and outputs."""
    STAMP.write_text(json.dumps(current_hashes(), indent=2, sort_keys=True) + "\n")


def stale_reasons() -> list[str]:
    """Why the committed build does not match its source, one line each; empty when current."""
    if not STAMP.exists():
        return ["no stamp: the paper has never been built here"]
    recorded = json.loads(STAMP.read_text())
    now = current_hashes()
    reasons = []
    for role in ("inputs", "outputs"):
        for path in sorted(set(recorded.get(role, {})) | set(now[role])):
            before, after = recorded.get(role, {}).get(path), now[role].get(path)
            if before != after:
                change = "added" if before is None else "removed" if after is None else "changed"
                reasons.append(f"{role[:-1]} {change} since the last build: {path}")
    return reasons


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check the build is current")
    args = parser.parse_args(argv)
    if args.check:
        reasons = stale_reasons()
        for reason in reasons:
            print(f"STALE {reason}")
        if reasons:
            print("Rebuild with: make paper   (python3 paper/build/build.py), then commit paper/.")
        return 1 if reasons else 0
    build_standalone()
    write_arxiv_sources(DRAFT.read_text())
    compile_arxiv()
    write_stamp()
    print(f"built: {OUT / 'score.pdf'} and {ARXIV / 'main.pdf'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
